// Creates a gitignored .env with fresh random secrets. Never prints secret values.
// Refuses to overwrite an existing .env (delete it yourself to regenerate).
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '.env');
if (existsSync(target)) {
  console.log('.env already exists; leaving it unchanged.');
  process.exit(0);
}
const secret = () => randomBytes(32).toString('hex');
const body = [
  '# Generated by scripts/init-env.mjs. Gitignored. Do not commit.',
  '# Loopback only by default. Real OIDC is required before any non-loopback HOST.',
  'HOST=127.0.0.1',
  'PORT=8787',
  'DATA_DIR=data',
  'PUBLIC_BASE_URL=http://127.0.0.1:8787',
  `HMAC_SECRET=${secret()}`,
  `TEKION_WEBHOOK_SECRET=${secret()}`,
  `CHANNEL_WEBHOOK_SECRET=${secret()}`,
  '# Dev only: enables X-Dev-User identities. Never set on a shared host.',
  'AUTH_TEST_BYPASS=1',
  'DEV_TOOLS=1',
  'RECALL_MODE=mock',
  '# AI provider: gemini | openai | off. "off" = rules-only, no model calls. Paste your key after the = sign.',
  'AI_PROVIDER=off',
  'GEMINI_API_KEY=',
  'OPENAI_API_KEY=',
  '',
].join('\n');
writeFileSync(target, body, { mode: 0o600 });
console.log('Created .env (mode 600) with random secrets. Values are not printed.');
